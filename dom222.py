#Задание:
#Посчитайте количество согласных букв в заданной строке, состоящей из русских букв.
#Формат входных данных:
#Дана произвольная строка text, содержащая русские буквы (в верхнем и/или нижнем регистре).
#Формат выходных данных:
#Вывести одно целое число — количество согласных букв в строке.

def count_consonants(text: str) -> int:
    # Множество русских согласных (в нижнем регистре)
    consonants = set()
    count = 0
    for char in text.lower():
        if char in consonants:
            count += 1
    return count

# Пример использования:
text = input()  # или передайте строку напрямую, например: text = "ПриветМир"
print(count_consonants(text))