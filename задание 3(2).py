# Дано число. Выведите в консоль сумму первой и последней цифры этого числа.

num = input().strip()          # читаем число как строку, чтобы легко взять первую и последнюю цифры
first_digit = int(num[0])      # первая цифра
last_digit = int(num[-1])      # последняя цифра
print(first_digit + last_digit)